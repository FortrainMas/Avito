SKIP_VALUES = {"Другое", "Своя услуга"}

KEYS = sorted(KEEP_KEYS | OTHER_KEYS, key=len, reverse=True)
KEY_PATTERN = re.compile(r"(?:^|(?<=\s))(" + "|".join(re.escape(key) for key in KEYS) + r")(?=\s|$)")
NUMBER_PATTERN = re.compile(r"\b\d+(?:[.,:]\d+)?\b")


def split_params(text: str) -> list[tuple[str, str]]:
    pairs = []
    key = ""
    position = 0
    for match in KEY_PATTERN.finditer(text):
        pairs.append((key, text[position:match.start()].strip()))
        key = match.group(1)
        position = match.end()
    pairs.append((key, text[position:].strip()))
    return pairs


def clean_params(text: str) -> str:
    values = []
    for key, value in split_params(text):
        value = NUMBER_PATTERN.sub(" ", value).strip()
        if key in KEEP_KEYS and value and value not in SKIP_VALUES and value not in values:
            values.append(value)
    return "; ".join(values)
